let currentLang = 'hi';

export function getLanguage() {
  const saved = localStorage.getItem('civicsolve_lang');
  if (saved && translations[saved]) {
    currentLang = saved;
  }
  return currentLang;
}

export function setLanguage(lang) {
  if (!translations[lang]) lang = 'hi';
  currentLang = lang;
  localStorage.setItem('civicsolve_lang', lang);
  applyTranslations();
  window.dispatchEvent(new CustomEvent('civicsolve:langchange', { detail: { lang } }));
  return currentLang;
}

export function t(key) {
  const dict = translations[currentLang] || translations['hi'];
  if (dict[key]) return dict[key];
  if (translations['hi'][key]) return translations['hi'][key];
  if (translations['en'][key]) return translations['en'][key];
  return key;
}

export function applyTranslations() {
  const dict = translations[currentLang] || translations['hi'];
  
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dict[key] || translations['hi'][key]) {
      el.textContent = dict[key] || translations['hi'][key];
    }
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (dict[key] || translations['hi'][key]) {
      el.setAttribute('placeholder', dict[key] || translations['hi'][key]);
    }
  });

  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    if (dict[key] || translations['hi'][key]) {
      el.setAttribute('title', dict[key] || translations['hi'][key]);
    }
  });

  document.documentElement.lang = currentLang;
  
  const currentLangLabel = document.getElementById('currentLangLabel');
  if (currentLangLabel) {
    const langObj = LANGUAGES.find(l => l.code === currentLang);
    if (langObj) {
      currentLangLabel.textContent = langObj.label;
    }
  }
}
